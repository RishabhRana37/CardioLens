    Age: float = Field(..., alias="Age")
    Weight: float = Field(..., alias="Weight")
    Height: float = Field(..., alias="Height")
    BMI: float = Field(..., alias="BMI")
    BP: float = Field(..., alias="BP")
    PR: float = Field(..., alias="PR")
    FBS: float = Field(..., alias="FBS")
