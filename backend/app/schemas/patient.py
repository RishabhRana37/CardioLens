    ESR: float = Field(..., alias="ESR")
    HB: float = Field(..., alias="HB")
    K: float = Field(..., alias="K")
    Na: float = Field(..., alias="Na")
    WBC: float = Field(..., alias="WBC")
    Lymph: float = Field(..., alias="Lymph")
    Neut: float = Field(..., alias="Neut")
    PLT: float = Field(..., alias="PLT")
    EF_TTE: float = Field(..., alias="EF-TTE")
    Function_Class: int = Field(..., alias="Function Class")
    Region_with_RWMA: int = Field(..., alias="Region with RWMA")
    Sex: Union[int, str] = Field(..., alias="Sex")
    DM: Union[int, str] = Field(..., alias="DM")
    HTN: Union[int, str] = Field(..., alias="HTN")
    Current_Smoker: Union[int, str] = Field(..., alias="Current Smoker")
    Ex_Smoker: Union[int, str] = Field(..., alias="Ex-Smoker")
