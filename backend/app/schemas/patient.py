    Q_Wave: Union[int, str] = Field(..., alias="Q Wave")
    ST_Elevation: Union[int, str] = Field(..., alias="ST Elevation")
    ST_Depression: Union[int, str] = Field(..., alias="ST Depression")
    T_inversion: Union[int, str] = Field(..., alias="T inversion")
    LVH: Union[int, str] = Field(..., alias="LVH")
